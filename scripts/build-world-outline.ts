// Writes src/lib/worldMap/worldOutline.ts, the land outline of the world map on the papers and dataset statistics
// pages (src/components/common/WorldMap.tsx), from Natural Earth's 1:110m land polygons (public domain,
// https://www.naturalearthdata.com/). Run it with the path or URL of ne_110m_land.geojson:
//
//   npx ts-node --transpile-only -O '{"module":"commonjs"}' scripts/build-world-outline.ts \
//     https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson
import fs from 'fs/promises';
import path from 'path';
import { MAP_BOUNDS } from '../src/lib/worldMap/map';

type Ring = [number, number][];
type Geometry = { type: 'Polygon'; coordinates: Ring[] } | { type: 'MultiPolygon'; coordinates: Ring[][] };

const OUTPUT = path.join('src', 'lib', 'worldMap', 'worldOutline.ts');

/** A number with one decimal, without a trailing `.0`. */
const format = (value: number): string => String(Math.round(value * 10) / 10);

/**
 * A ring as SVG path commands in the map's projection (x = longitude, y = −latitude), relative after the first
 * point, at a precision of 0.1°.
 */
function ringPath(ring: Ring): string {
  const points = ring.map(([lon, lat]) => [Math.round(lon * 10), Math.round(-lat * 10)]);
  const [first, ...rest] = points;
  let [x, y] = first;
  const steps: string[] = [];
  for (const [nextX, nextY] of rest) {
    if (nextX === x && nextY === y) continue;
    steps.push(`${format((nextX - x) / 10)} ${format((nextY - y) / 10)}`);
    [x, y] = [nextX, nextY];
  }
  return `M${format(first[0] / 10)} ${format(first[1] / 10)}l${steps.join(' ')}z`;
}

async function main(source: string): Promise<void> {
  const text = /^https?:/.test(source)
    ? await (await fetch(source)).text()
    : await fs.readFile(source, 'utf8');
  const { features } = JSON.parse(text) as { features: { geometry: Geometry }[] };
  const polygons = features.flatMap(({ geometry }) =>
    geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates
  );
  // Polygons entirely south of the map (Antarctica) are left out.
  const shown = polygons.filter(([outer]) => outer.some(([, lat]) => lat > MAP_BOUNDS.south));
  const outline = shown.flatMap(rings => rings.map(ringPath)).join('');
  await fs.writeFile(
    OUTPUT,
    `// Generated by scripts/build-world-outline.ts from Natural Earth's 1:110m land polygons (public domain,\n` +
      `// https://www.naturalearthdata.com/). Do not edit by hand.\n\n` +
      `/** The land, as an SVG path in the map's projection (see \`project\` in map.ts). */\n` +
      `export const WORLD_LAND_PATH =\n  '${outline}';\n`
  );
  console.info(`Wrote ${OUTPUT}: ${shown.length} polygons, ${outline.length} characters.`);
}

main(process.argv[2] ?? '').catch((err: unknown) => {
  console.error(err);
  process.exitCode = 1;
});
